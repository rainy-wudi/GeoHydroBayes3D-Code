def reset_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)

    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def safe_r2(y_true, y_pred):
    if np.var(y_true) <= 1e-15:
        return np.nan
    return r2_score(y_true, y_pred)


class GroupMeanDNN(nn.Module):

    def __init__(self):
        super().__init__()

        self.net = nn.Sequential(
            nn.Linear(6, 32),
            nn.ReLU(),
            nn.Dropout(DROPOUT),

            nn.Linear(32, 64),
            nn.ReLU(),
            nn.Dropout(DROPOUT),

            nn.Linear(64, 32),
            nn.ReLU(),

            nn.Linear(32, 23)
        )

    def forward(self, x):
        return self.net(x)


def train_fixed_epochs(
    X_train,
    Y_train,
    X_pred,
    epochs,
    seed,
    device
):

    reset_seed(seed)

    scaler_X = StandardScaler()
    scaler_Y = StandardScaler()

    X_train_s = scaler_X.fit_transform(X_train)
    Y_train_s = scaler_Y.fit_transform(Y_train)
    X_pred_s = scaler_X.transform(X_pred)

    Xtr_t = torch.tensor(
        X_train_s,
        dtype=torch.float32
    )

    Ytr_t = torch.tensor(
        Y_train_s,
        dtype=torch.float32
    )

    Xpred_t = torch.tensor(
        X_pred_s,
        dtype=torch.float32
    )

    generator = torch.Generator().manual_seed(seed)

    loader = DataLoader(
        TensorDataset(Xtr_t, Ytr_t),
        batch_size=BATCH_SIZE,
        shuffle=True,
        generator=generator
    )

    model = GroupMeanDNN().to(device)

    criterion = nn.MSELoss()

    optimizer = optim.Adam(
        model.parameters(),
        lr=LR,
        weight_decay=WEIGHT_DECAY
    )

    losses = []

    for epoch in range(epochs):

        model.train()

        batch_losses = []

        for bx, by in loader:

            bx = bx.to(device)
            by = by.to(device)

            optimizer.zero_grad()

            pred = model(bx)

            loss = criterion(pred, by)

            loss.backward()

            optimizer.step()

            batch_losses.append(loss.item())

        losses.append(
            float(np.mean(batch_losses))
        )

    model.eval()

    with torch.no_grad():

        pred_s = model(
            Xpred_t.to(device)
        ).cpu().numpy()

    pred = scaler_Y.inverse_transform(pred_s)

    return (
        model,
        scaler_X,
        scaler_Y,
        pred,
        losses
    )


