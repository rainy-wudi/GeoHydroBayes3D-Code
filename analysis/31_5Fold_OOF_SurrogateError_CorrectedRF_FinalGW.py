"""
31_5Fold_OOF_SurrogateError_CorrectedRF_FinalGW.py

STEP 8
------
Strict 5-fold group-level out-of-fold (OOF) surrogate-error analysis for the
corrected-random-field FinalGW database.

Scientific target
-----------------
The DNN represents the conditional group-mean response:

    f_DNN(theta) ~= E[h | theta]

For every one of the 50 independent parameter groups, an OOF prediction is
generated by a network that did NOT train on that group.

OOF residual definition
-----------------------
    e_surr = h_Abaqus_groupmean - h_DNN_OOF

Outputs
-------
1) OOF predictions for all 50 groups
2) OOF residuals (50 x 23)
3) deterministic surrogate bias:
       b_surr = mean(e_surr)
4) raw surrogate-error covariance
5) Ledoit-Wolf shrinkage covariance:
       Sigma_surr_LW
6) per-borehole OOF metrics and bias/std diagnostics
7) overall OOF metrics
8) final production DNN refit on ALL 50 groups using the FIXED epoch count
   selected in Step 7 (253 epochs), plus all-50 scalers

Important
---------
- KFold is performed over the 50 P-groups, not over 1000 realization rows.
- Architecture/hyperparameters are frozen from Step 7.
- Number of epochs is frozen at BEST_EPOCH = 253 from Step 7.
- Each fold fits its own X/Y scalers using only its 40 training groups.
- Held-out groups are never used for fitting scalers or weights.
- No physics penalty is used.
"""

